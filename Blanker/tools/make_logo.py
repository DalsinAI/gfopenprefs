#!/usr/bin/env python3
"""Writes Blanker/src/bl_logo.h: the AmiCradle logo for the show's last card,
from amicradle's launcher/icons/amicradle-logo-192.png. The picture is laid on
the show's background colour, cut to its own edges, brought down to
BL_LOGO_COLOURS colours and run-length coded as (count, colour) pairs, a row
after another. Colour 0 is the background.
    python3 Blanker/tools/make_logo.py /path/to/amicradle-logo-192.png > Blanker/src/bl_logo.h
MIT, Copyright (c) 2026 AmiCradle Team."""
import sys
from PIL import Image

BG = (13, 16, 19)          # openblanker.c's full[0]
COLOURS = 24

def main(path):
    im = Image.open(path).convert("RGBA")
    im = im.crop(im.getbbox())
    flat = Image.new("RGB", im.size, BG)
    flat.paste(im, mask=im.split()[3])
    q = flat.quantize(COLOURS - 1, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:(COLOURS - 1) * 3]
    px, alpha = q.load(), im.split()[3].load()
    w, h = im.size
    runs = []
    for y in range(h):
        for x in range(w):
            c = 0 if alpha[x, y] < 24 else px[x, y] + 1
            if runs and runs[-1][1] == c and runs[-1][0] < 255:
                runs[-1][0] += 1
            else:
                runs.append([1, c])
    out = ["/* Generated by Blanker/tools/make_logo.py from amicradle's launcher/icons/amicradle-logo-192.png. Do not edit.",
           " * The AmiCradle logo for the show's last card: (count, colour) pairs, row after row; colour 0 is the",
           " * background, colour n is bl_logo_rgb[n - 1]. MIT, Copyright (c) 2026 AmiCradle Team. */",
           "#ifndef BL_LOGO_H", "#define BL_LOGO_H",
           "#define BL_LOGO_W %d" % w, "#define BL_LOGO_H_PX %d" % h, "#define BL_LOGO_COLOURS %d" % COLOURS,
           "#define BL_LOGO_RUNS %d" % len(runs),
           "static const unsigned char bl_logo_rgb[BL_LOGO_COLOURS - 1][3] = {"]
    out += ["    " + " ".join("{%d,%d,%d}," % tuple(pal[i * 3:i * 3 + 3]) for i in range(j, min(j + 6, COLOURS - 1))) for j in range(0, COLOURS - 1, 6)]
    out += ["};", "static const unsigned char bl_logo_rle[BL_LOGO_RUNS * 2] = {"]
    flat_runs = [v for r in runs for v in r]
    out += ["    " + ",".join(str(v) for v in flat_runs[i:i + 40]) + "," for i in range(0, len(flat_runs), 40)]
    out += ["};", "",
            "/* how many screen pixels a logo pixel is, on a screen H high: 1 up to 959, 2 from 960 (1080), 4 at 2160 */",
            "static int bl_logo_scale(int H) { int s = H / 480; return s < 1 ? 1 : s; }",
            "/* the left edge that centres the logo on a screen W wide */",
            "static int bl_logo_left(int W, int s) { return (W - BL_LOGO_W * s) / 2; }",
            "#endif"]
    print("\n".join(out))

if __name__ == "__main__":
    main(sys.argv[1])
